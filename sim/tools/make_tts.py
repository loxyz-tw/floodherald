"""Prepare the two Mandarin warning clips and their captions (CPU only).

Run from the sim/ directory:

    uv run --no-project tools/make_tts.py

The speech itself was generated by hand in Google AI Studio on 2026-10-13,
not by this script:

- Model: Gemini 3.8 Flash TTS (`gemini-3.8-flash-tts`), Playground
- Speaker: Fola (default speaker, default description); Style and
  Expression left unset; the text box held only the line in CLIPS below
- Downloaded as 24 kHz mono WAV and kept unchanged in assets/audio/source/

This script trims leading and trailing silence, pads PAD_S on each side,
resamples to 48 kHz, normalises the peak to PEAK_DBFS and writes
assets/audio/warn_zone.wav, warn_flood.wav (16-bit PCM) and captions.json.
"""

import json
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

OUT_RATE = 48000
PAD_S = 0.15
PEAK_DBFS = -1.0
SILENCE_DBFS = -40.0  # samples quieter than this at either end are trimmed

CLIPS = {
    "warn_zone.wav": {
        "source": "warn_zone_gemini.wav",
        "zh": "您已進入禁止戲水區，請立即上岸。",
        "en": "You are in a no-swimming zone. Please leave the water now.",
    },
    "warn_flood.wav": {
        "source": "warn_flood_gemini.wav",
        "zh": "上游暴洪，請立即離開河床，往高處移動。",
        "en": "Flash flood upstream. Leave the riverbed and move to higher ground now.",
    },
}

OUT_DIR = Path(__file__).resolve().parent.parent / "assets" / "audio"
SRC_DIR = OUT_DIR / "source"


def trim(audio: np.ndarray) -> np.ndarray:
    loud = np.flatnonzero(np.abs(audio) > 10 ** (SILENCE_DBFS / 20))
    return audio[loud[0] : loud[-1] + 1]


def main() -> None:
    captions = {}
    for name, clip in CLIPS.items():
        audio, rate = sf.read(SRC_DIR / clip["source"], dtype="float64")
        if audio.ndim > 1:
            audio = audio.mean(axis=1)
        audio = resample_poly(trim(audio), OUT_RATE, rate)
        pad = np.zeros(int(PAD_S * OUT_RATE))
        audio = np.concatenate([pad, audio, pad])
        audio *= 10 ** (PEAK_DBFS / 20) / np.max(np.abs(audio))
        sf.write(OUT_DIR / name, audio, OUT_RATE, subtype="PCM_16")
        captions[name] = {
            "zh": clip["zh"],
            "en": clip["en"],
            "seconds": round(len(audio) / OUT_RATE, 2),
        }

    with open(OUT_DIR / "captions.json", "w", encoding="utf-8") as f:
        json.dump(captions, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(json.dumps(captions, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
